/**
 * Writes global.css from src/design/tokens.ts so className utilities and JS colors share
 * one source. `--check` fails when the committed file is stale (CI Quality runs it).
 * Regenerate with `node --no-warnings --experimental-strip-types scripts/design-tokens.mjs`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ANDROID_FONT_FAMILY, COLOR_CSS_NAMES, RADIUS, SHADOW_FLOAT, SHADOW_GLASS, TEXT_RAMP, darkPalette, interTracking, lightPalette } from "../src/design/tokens.ts";

// Resolved from this file, like the token import, so the script works from any directory.
const TARGET = fileURLToPath(new URL("../global.css", import.meta.url));

const colors = (palette) => Object.entries(COLOR_CSS_NAMES).map(([key, name]) => `--color-${name}: ${palette[key]};`);
const indent = (lines, depth) => lines.map((line) => `${"  ".repeat(depth)}${line}`).join("\n");

const theme = [
  // Clearing Tailwind's defaults makes any color, radius, or text size outside the tokens a no-op class.
  "--color-*: initial;",
  "--radius-*: initial;",
  "--text-*: initial;",
  "--shadow-*: initial;",
  ...colors(lightPalette),
  ...Object.entries(RADIUS).map(([name, value]) => `--radius-${name}: ${value}px;`),
  ...Object.entries(TEXT_RAMP).flatMap(([name, { size, lineHeight, weight }]) => [
    `--text-${name}: ${size}px;`,
    `--text-${name}--line-height: ${lineHeight}px;`,
    ...(weight ? [`--text-${name}--font-weight: ${weight};`] : []),
  ]),
  `--shadow-float: ${SHADOW_FLOAT};`,
  `--shadow-glass: ${SHADOW_GLASS};`,
];

// Android text: each ramp class takes the Inter family and Inter's tracking for its size; the ramp's
// default weight and `font-*` classes pick the face. Code keeps its monospace.
const androidText = Object.entries(TEXT_RAMP).filter(([name]) => name !== "code").map(([name, { size }]) =>
  `.text-${name} { font-family: ${ANDROID_FONT_FAMILY}; letter-spacing: ${interTracking(size)}px; }`);

const css = `/* Generated by scripts/design-tokens.mjs from src/design/tokens.ts. Do not edit. */
@import "tailwindcss";
@import "uniwind";

@source not "./reference";
@source not "./landing";
@source not "./docs";

@theme {
${indent(theme, 1)}
}

@media android {
${indent(androidText, 1)}
}

/* Runtime overrides (pure black, Config theme, font scale) go through Uniwind.updateCSSVariables. */
@layer theme {
  :root {
    @variant light {
${indent(colors(lightPalette), 3)}
    }
    @variant dark {
${indent(colors(darkPalette), 3)}
    }
  }
}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(TARGET, "utf8") !== css) {
    console.error(`${TARGET} is stale. Run \`node --no-warnings --experimental-strip-types scripts/design-tokens.mjs\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${TARGET} matches src/design/tokens.ts.`);
} else {
  writeFileSync(TARGET, css);
  console.log(`Wrote ${TARGET}.`);
}
